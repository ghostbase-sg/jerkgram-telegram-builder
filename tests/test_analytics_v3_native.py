from pathlib import Path
import os
import json
import threading
import time
from http.server import BaseHTTPRequestHandler, HTTPServer
import shutil
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
PAYLOAD = ROOT / 'scripts/jerkgram_analytics_v3_payload/JerkgramAnalyticsV3.swift'

class AnalyticsV3NativeTests(unittest.TestCase):
    def test_production_transport_stays_disabled(self):
        source = PAYLOAD.read_text()
        self.assertIn('static let productionTransportEnabled = false', source)
        self.assertNotIn('ADMIN_TOKEN', source)
        for field in ('analyticsDayId', 'identifierForVendor', 'advertisingIdentifier'):
            self.assertNotIn(field, source)

    def test_actual_swift_core(self):
        if not shutil.which('swiftc'):
            if os.environ.get('JERKGRAM_REQUIRE_NATIVE_SWIFT') == '1':
                self.fail('Swift compiler required by native CI')
            self.skipTest('Swift compiler unavailable')
        fixture = (ROOT / 'tests/analytics_v3_native/main.swift').read_text()
        with tempfile.TemporaryDirectory() as directory:
            main = Path(directory) / 'main.swift'
            main.write_text(fixture)
            binary = Path(directory) / 'analytics-tests'
            subprocess.run(['swiftc', str(PAYLOAD), str(main), '-o', str(binary)], check=True)
            subprocess.run([str(binary)], check=True)
            received = []
            class Handler(BaseHTTPRequestHandler):
                def do_POST(self):
                    body = self.rfile.read(int(self.headers['Content-Length']))
                    scenario = self.headers.get('X-Jerkgram-Test-Scenario')
                    received.append((self.path, self.headers.get('Content-Type'), body, scenario))
                    count = sum(item[3] == scenario for item in received)
                    status = 400 if scenario == 'bad' else 503 if scenario == 'retry' and count == 1 else 200
                    if scenario == 'off':
                        time.sleep(0.5)
                    self.send_response(status); self.end_headers()
                    try:
                        self.wfile.write(b'{"ok":true,"schema":3,"processed":4,"newEvents":0,"timezone":"Europe/Moscow"}')
                    except (BrokenPipeError, ConnectionResetError):
                        pass
                def log_message(self, *args):
                    pass
            server = HTTPServer(('127.0.0.1', 0), Handler)
            thread = threading.Thread(target=server.serve_forever, daemon=True); thread.start()
            try:
                for scenario in ('ack', 'bad', 'retry', 'off', 'disabled'):
                    subprocess.run([str(binary), f'http://127.0.0.1:{server.server_port}/v3/events', scenario], check=True, timeout=10)
            finally:
                server.shutdown(); server.server_close(); thread.join()
            self.assertEqual(sum(item[3] == 'ack' for item in received), 1)
            self.assertEqual(sum(item[3] == 'bad' for item in received), 1)
            retries = [item[2] for item in received if item[3] == 'retry']
            self.assertEqual(len(retries), 2)
            self.assertEqual(retries[0], retries[1])
            self.assertFalse(any(item[3] == 'disabled' for item in received))
            self.assertLessEqual(sum(item[3] == 'off' for item in received), 1)
            for path, content_type, body, scenario in received:
                self.assertEqual((path, content_type), ('/v3/events', 'application/json'))
                self.assertLessEqual(len(body), 16 * 1024)
                payload = json.loads(body)
                self.assertEqual(payload['schema'], 3)
                self.assertTrue(1 <= len(payload['events']) <= 20)
                self.assertEqual({e['eventName'] for e in payload['events']}, {'install_registered', 'app_opened', 'session_started', 'session_engaged'})
            # These are generated by the actual native runtime and use test-only
            # random UUIDs; they contain no installation/device user data.
            artifacts = Path(os.environ.get('JERKGRAM_ANALYTICS_NATIVE_ARTIFACT_DIR', str(ROOT / 'artifacts/analytics-v3-native')))
            artifacts.mkdir(parents=True, exist_ok=True)
            (artifacts / 'actual-loopback-payload.json').write_bytes(received[0][2])
            (artifacts / 'loopback-results.json').write_text(json.dumps({'ack': 1, 'bad': 1, 'retry': len(retries), 'off': sum(item[3] == 'off' for item in received), 'disabled': 0}, indent=2))

if __name__ == '__main__':
    unittest.main()
